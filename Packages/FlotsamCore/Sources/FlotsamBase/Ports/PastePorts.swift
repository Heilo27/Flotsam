/// The one definition of how Flotsam marks its own pasteboard writes (FR-001-03). It lives in Base, not Paste, because
/// Capture checks the marker and Capture may not import Paste.
public enum OwnWrite {
    /// The nspasteboard.org convention: tells other clipboard managers the content was not typed by the user.
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    /// Flotsam's own marker.
    public static let markerType = "com.flotsam.own-write"
    /// Every type added to every Flotsam pasteboard write, with empty data.
    public static let types = [autoGeneratedType, markerType]

    /// The marker representations to append to a write.
    public static var markers: [PasteboardRepresentation] {
        types.map { PasteboardRepresentation(uti: $0, data: Data()) }
    }
}

/// The `changeCount` values Flotsam's own writes produced, newest last (FR-001-03). Paste records, Capture asks.
public final class OwnWriteLedger: Sendable {
    /// FR-001-03 keeps the last 8.
    static let capacity = 8
    private let counts = OSAllocatedUnfairLock(initialState: [Int]())

    public init() {}

    public func record(changeCount: Int) {
        counts.withLock { counts in
            counts.append(changeCount)
            if counts.count > Self.capacity { counts.removeFirst(counts.count - Self.capacity) }
        }
    }

    public func contains(changeCount: Int) -> Bool {
        counts.withLock { $0.contains(changeCount) }
    }
}
