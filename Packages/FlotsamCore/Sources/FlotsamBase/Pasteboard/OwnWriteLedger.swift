import Foundation

/// Marker type identifiers that other apps and Flotsam put on the pasteboard (FR-001-03, FR-001-04, FR-001-13,
/// FR-001-14). One home, so the writer and the reader of a marker cannot disagree about its spelling.
public enum PasteboardMarkers {
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Bundle identifier of the app that wrote the pasteboard, when it says so.
    public static let source = "org.nspasteboard.source"
    /// Universal Clipboard from another device.
    public static let remoteClipboard = "com.apple.is-remote-clipboard"
    public static let ownWrite = "com.flotsam.own-write"

    /// Types whose mere presence means "do not store" (FR-001-04 gate 3). Presence alone rejects, never the data.
    public static let neverStore: [String] = [concealed, transient, autoGenerated]

    /// The markers every Flotsam pasteboard write carries (FR-001-03), in write order. The one list: the ledger, the
    /// clipboard restore and Copy Diagnostics all read it, so a marker added here reaches every writer.
    public static let ownWriteTypes: [String] = [autoGenerated, ownWrite]
}

/// Remembers which pasteboard changes Flotsam made itself, so capture does not store them again (FR-001-03).
///
/// Every write by Flotsam (paste-back, trigger expansion, Copy Diagnostics, copy fallbacks) goes through `write`,
/// which adds the own-write and auto-generated markers and records the resulting `changeCount`. Capture then rejects
/// a change that is recorded here or that carries the own-write type. Main-actor, like the port it wraps.
@MainActor
public final class OwnWriteLedger {
    /// Only the most recent writes matter: capture polls twice a second, so an older count is never still pending.
    private static let capacity = 8

    private var changeCounts: [Int] = []

    public init() {}

    public func contains(changeCount: Int) -> Bool { changeCounts.contains(changeCount) }

    /// Writes `representations` plus the markers (empty data) and records the `changeCount` the write produced.
    public func write(_ representations: [PasteboardRepresentation], to pasteboard: any PasteboardPort) -> FlotsamResult<Int> {
        let marked = representations + PasteboardMarkers.ownWriteTypes.map { PasteboardRepresentation(uti: $0, data: Data()) }
        let result = pasteboard.write(marked)
        if case .success(let changeCount) = result {
            changeCounts.append(changeCount)
            if changeCounts.count > Self.capacity { changeCounts.removeFirst(changeCounts.count - Self.capacity) }
        }
        return result
    }
}
