import FlotsamBase
import FlotsamPaste
import FlotsamStorage
import Foundation
import Testing
@testable import FlotsamLibrary

// TASK-504 (Worf, blind delta QA), Ryan's ruling on Command-C in the Library: copy-only through PasteService, gated on
// secure rows, yields to a search-field text selection, disabled with several rows selected (as Shift-Return is).
// Every expected value is a literal. The Keychain vault and the owner check are fakes: nothing here touches the real
// Keychain or LocalAuthentication.

@MainActor
@Suite struct Frd003CommandCAdversarialTests {
    private static let revealedTypes = [
        "com.flotsam.own-write", "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.ConcealedType",
        "public.utf8-plain-text",
    ]

    // given a secure row selected and text selected in the search field, when Command-C is pressed,
    // then the Library does not own the key: no prompt, no decrypt, nothing written, no error, panel still open.
    // Red under: ignoring searchHasSelection in LibraryKeyMap.command.
    @Test("QA-504-1 Command-C with search selection on a secure row: no auth prompt, no vault call, nothing written")
    func searchSelectionOnSecureRowIsInert() async throws {
        let rig = try await SecureContractRig()
        let secure = try await rig.addSecure()
        await rig.open()
        rig.select(secure)
        let writesBefore = rig.pasteboard.written.count
        let handled = rig.model.handle(LibraryKeyStroke(.character("c"), .command), searchHasSelection: true)
        #expect(handled == false)
        #expect(rig.model.pasteTask == nil)
        await rig.model.settled()
        #expect(rig.authenticator.requests == 0)
        #expect(rig.vault.opens == 0)
        #expect(rig.log.events == [])
        #expect(rig.pasteboard.written.count == writesBefore)
        #expect(rig.reported.errors.isEmpty)
        #expect(rig.host.hideCount == 0)
        #expect(rig.keys.posts == 0)
        rig.cleanUp()
    }

    // given two rows selected (one secure), when Command-C is pressed, then it does what Shift-Return does with the
    // same selection: nothing. No prompt, no decrypt, no write, no error, no paste task, panel open.
    // Red under: dropping the single-row guard for the copy-only command, or routing Command-C around pasteSelected.
    @Test("QA-504-2 Command-C with two rows selected is disabled, identical to Shift-Return")
    func multiSelectionDisablesCommandC() async throws {
        let rig = try await SecureContractRig()
        let secure = try await rig.addSecure(secondsAgo: 0)
        let plain = try await rig.addPlain("plain-text", secondsAgo: 10)
        await rig.open()
        rig.select(secure)
        rig.model.extend(to: plain)
        #expect(rig.model.selection.count == 2)
        let writesBefore = rig.pasteboard.written.count

        let shiftReturnHandled = await rig.press(.returnKey, .shift)
        let afterShiftReturn = (rig.authenticator.requests, rig.vault.opens, rig.pasteboard.written.count, rig.host.hideCount)

        let commandCHandled = await rig.press(.character("c"), .command)
        let afterCommandC = (rig.authenticator.requests, rig.vault.opens, rig.pasteboard.written.count, rig.host.hideCount)

        #expect(commandCHandled == shiftReturnHandled)
        #expect(afterShiftReturn == (0, 0, writesBefore, 0))
        #expect(afterCommandC == (0, 0, writesBefore, 0))
        #expect(rig.reported.errors.isEmpty)
        #expect(rig.keys.posts == 0)
        #expect(rig.model.selection.count == 2)
        rig.cleanUp()
    }

    // given two rows were selected and the selection is reduced to one, when Command-C is pressed, then the one row is copied
    // (the disable is about the selection count, not a stuck flag).
    @Test("QA-504-3 Command-C works again once the selection is back to one plain row")
    func singleSelectionAfterMultiCopies() async throws {
        let rig = try await SecureContractRig()
        let first = try await rig.addPlain("first-text", secondsAgo: 0)
        let second = try await rig.addPlain("second-text", secondsAgo: 10)
        await rig.open()
        rig.select(first)
        rig.model.extend(to: second)
        let writesBefore = rig.pasteboard.written.count
        await rig.press(.character("c"), .command)
        #expect(rig.pasteboard.written.count == writesBefore)
        rig.select(second)
        await rig.press(.character("c"), .command)
        #expect(rig.pasteboard.written.count == writesBefore + 1)
        #expect(rig.lastText == "second-text")
        rig.cleanUp()
    }

    // given a plain text row, when Command-C is pressed, then exactly one write, the row's text, through PasteService's
    // copy-only mode: no key event posted, panel closed, and no vault or authenticator call of any kind.
    // Red under: a Keychain/LocalAuthentication call on plain rows; routing around PasteService (a paste would post keys).
    @Test("QA-504-4 Command-C on a plain row: no vault or auth call, one copy-only write, no key posted, panel closes")
    func plainRowTouchesNoSecurityLayer() async throws {
        let rig = try await SecureContractRig()
        let plain = try await rig.addPlain("plain-text", secondsAgo: 0)
        let other = try await rig.addPlain("other-text", secondsAgo: 10)
        await rig.open()
        rig.select(plain)
        let writesBefore = rig.pasteboard.written.count
        let handled = await rig.press(.character("c"), .command)
        #expect(handled)
        #expect(rig.log.events == [])
        #expect(rig.vault.opens == 0)
        #expect(rig.authenticator.requests == 0)
        #expect(rig.pasteboard.written.count == writesBefore + 1)
        #expect(rig.lastText == "plain-text")
        #expect(rig.lastText != "other-text")
        #expect(!rig.lastTypes.contains("org.nspasteboard.ConcealedType"))
        #expect(rig.keys.posts == 0)
        #expect(rig.host.hideCount == 1)
        #expect(rig.reported.errors.isEmpty)
        _ = other
        rig.cleanUp()
    }

    // given a secure row and a successful owner check, when Command-C is pressed, then one prompt, one decrypt after it,
    // the concealed write (four literal types), no key posted, panel closes; the other row is untouched.
    @Test("QA-504-5 Command-C on a secure row after auth: auth precedes decrypt, concealed copy-only write, no paste")
    func secureRowAfterAuth() async throws {
        let rig = try await SecureContractRig()
        let secure = try await rig.addSecure()
        _ = try await rig.addPlain("plain-text", secondsAgo: 10)
        await rig.open()
        rig.select(secure)
        let writesBefore = rig.pasteboard.written.count
        let handled = await rig.press(.character("c"), .command)
        #expect(handled)
        #expect(rig.log.events == ["auth", "open"])
        #expect(rig.pasteboard.written.count == writesBefore + 1)
        #expect(rig.lastText == "hunter2-secret")
        #expect(rig.lastTypes == Self.revealedTypes)
        #expect(rig.keys.posts == 0)
        #expect(rig.host.hideCount == 1)
        #expect(rig.reported.errors.isEmpty)
        rig.cleanUp()
    }

    // given a cancelled prompt, when Command-C is pressed, then no write, no decrypt, panel stays, one LIB-OS-002.
    @Test("QA-504-6 Command-C on a secure row with a cancelled prompt: no decrypt, no write, panel stays open")
    func secureRowCancelled() async throws {
        let rig = try await SecureContractRig(answers: [SecureContractAuthenticator.cancelled])
        let secure = try await rig.addSecure()
        await rig.open()
        rig.select(secure)
        let writesBefore = rig.pasteboard.written.count
        await rig.press(.character("c"), .command)
        #expect(rig.log.events == ["auth"])
        #expect(rig.vault.opens == 0)
        #expect(rig.pasteboard.written.count == writesBefore)
        #expect(rig.host.hideCount == 0)
        #expect(rig.reported.errors.map(\.code) == [.libOs002])
        rig.cleanUp()
    }

    // The key map is data (FR-003-08): Command-C resolves to the copy-only paste, and only the selection flag removes it.
    // Red under: dropping the table row; ignoring searchHasSelection; mapping it to another command.
    @Test("QA-504-7 key map: Command-C is copy-only paste; with a search selection it is not the Library's; Shift-Command-C is not bound")
    func keyMapRow() {
        let plain = LibraryKeyMap.Context(searchIsEmpty: true, viewMode: .list)
        let selected = LibraryKeyMap.Context(searchIsEmpty: false, viewMode: .grid, searchHasSelection: true)
        let cmdC = LibraryKeyStroke(.character("c"), .command)
        #expect(LibraryKeyMap.command(for: cmdC, in: plain) == .paste(.copyOnly))
        #expect(LibraryKeyMap.command(for: cmdC, in: selected) == nil)
        #expect(LibraryKeyMap.command(for: LibraryKeyStroke(.character("c"), [.command, .shift]), in: plain) == nil)
        #expect(LibraryKeyMap.command(for: LibraryKeyStroke(.character("c")), in: plain) == nil)
        // the selection flag only affects Command-C
        #expect(LibraryKeyMap.command(for: LibraryKeyStroke(.character("y"), .command), in: selected) == .togglePreview)
    }
}
