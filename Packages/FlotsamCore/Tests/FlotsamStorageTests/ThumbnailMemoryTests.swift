import Foundation
import Testing
import FlotsamBase
@testable import FlotsamStorage

// S5 "Invisible on the machine" (TASK-373): ingest writes thumbnails to disk only, the memory LRU fills only when a
// thumbnail is read, and `releaseMemory()` empties it without touching the disk copies (FR-007-07, FR-003-13).
// The LRU is observed through `ThumbnailCache.cached`, the layer the idle footprint is made of; disk is observed by
// file bytes and through a SECOND database instance, so no answer can come from the first instance's memory.

@Suite struct ThumbnailMemoryTests {
    private func thumbPath(_ rig: Rig, _ id: UUID, _ edge: Int) -> URL {
        rig.store.thumbsDir.appendingPathComponent("\(id.uuidString)-\(edge).jpg")
    }

    private func cached(_ db: FlotsamDatabase, _ id: UUID, _ size: ThumbnailSize) async -> Data? {
        await db.thumbnails.cached(ThumbnailCache.key(id, size))
    }

    private func ingestWarmed(_ rig: Rig, key: String = "img") async throws -> UUID {
        let id = try await rig.create(rig.image(key, TestImage.make(width: 1200, height: 800, format: .png)))
        let warmed = await waitUntil { rig.store.exists(thumbPath(rig, id, 256)) && rig.store.exists(thumbPath(rig, id, 512)) }
        try #require(warmed, "warm-up never wrote both thumbnails")
        return id
    }

    private func freshDatabase(_ rig: Rig) async throws -> FlotsamDatabase {
        try await FlotsamDatabase.open(folder: rig.store.root, fileSystem: LocalFileSystem(), clock: rig.store.clock).get()
    }

    /// OC-S5-01. Given a new image ingested and its thumbnails written, when nobody has read a thumbnail, then the
    /// memory LRU holds neither size, both JPEG files are on disk, and a fresh instance (cold cache) serves both
    /// sizes from disk byte for byte and only then holds them. Goes red if ingest warms through `thumbnail()` (LRU
    /// filled while idle) or if the disk write is dropped (cold path returns regenerated bytes that differ or nil).
    @Test("OC-S5-01 ingest leaves the memory LRU empty; a cold instance still serves the new item from disk")
    func ingestDoesNotFillLRUButColdReadWorks() async throws {
        let rig = try await Rig.make()
        defer { rig.cleanUp() }

        // given / when: one ingested image, warm-up finished
        let id = try await ingestWarmed(rig)

        // then: nothing in memory, both files on disk
        #expect(await cached(rig.store.database, id, .grid) == nil)
        #expect(await cached(rig.store.database, id, .preview) == nil)
        let grid = try Data(contentsOf: thumbPath(rig, id, 256))
        let preview = try Data(contentsOf: thumbPath(rig, id, 512))
        #expect(TestImage.inspect(grid)?.width == 256)
        #expect(TestImage.inspect(preview)?.width == 512)

        // when: a cold instance is asked (the panel opening after a relaunch)
        let fresh = try await freshDatabase(rig)
        #expect(await cached(fresh, id, .grid) == nil, "precondition: cold")
        let servedGrid = await fresh.thumbnail(itemId: id, size: .grid)
        let servedPreview = await fresh.thumbnail(itemId: id, size: .preview)

        // then: the disk bytes come back unchanged, and reading is what fills the LRU
        #expect(servedGrid == grid)
        #expect(servedPreview == preview)
        #expect(await cached(fresh, id, .grid) == grid)
        #expect(await cached(fresh, id, .preview) == preview)
    }

    /// OC-S5-02. Given an item whose grid and preview thumbnails are in the LRU, when `releaseMemory()` runs, then the
    /// LRU holds neither, both disk files are byte-identical to before, a neighbour item's files are untouched, and
    /// the next request serves the same bytes again (and refills the LRU). Goes red if `releaseMemory()` does not
    /// empty the LRU, deletes disk thumbnails, or leaves the cache unusable.
    @Test("OC-S5-02 releaseMemory empties the LRU, keeps every disk thumbnail, and reads still work")
    func releaseMemoryEmptiesLRUOnly() async throws {
        let rig = try await Rig.make()
        defer { rig.cleanUp() }
        let id = try await ingestWarmed(rig, key: "a")
        let neighbour = try await ingestWarmed(rig, key: "b")
        let db = rig.store.database
        let gridBefore = try #require(await db.thumbnail(itemId: id, size: .grid))
        let previewBefore = try #require(await db.thumbnail(itemId: id, size: .preview))
        _ = await db.thumbnail(itemId: neighbour, size: .grid)
        #expect(await cached(db, id, .grid) == gridBefore, "precondition: primed")
        #expect(await cached(db, id, .preview) == previewBefore, "precondition: primed")
        let neighbourFile = try Data(contentsOf: thumbPath(rig, neighbour, 256))

        await db.releaseMemory()

        #expect(await cached(db, id, .grid) == nil)
        #expect(await cached(db, id, .preview) == nil)
        #expect(await cached(db, neighbour, .grid) == nil)
        #expect(try Data(contentsOf: thumbPath(rig, id, 256)) == gridBefore)
        #expect(try Data(contentsOf: thumbPath(rig, id, 512)) == previewBefore)
        #expect(try Data(contentsOf: thumbPath(rig, neighbour, 256)) == neighbourFile)
        #expect(try rig.itemCount() == 2)
        #expect(await db.thumbnail(itemId: id, size: .grid) == gridBefore)
        #expect(await cached(db, id, .grid) == gridBefore, "the cache refills after a release")
    }

    /// OC-S5-03. Given an empty LRU, when `releaseMemory()` runs on it, then nothing throws, it stays empty and a
    /// thumbnail read afterwards still works (the 0 case of the release).
    @Test("OC-S5-03 releaseMemory on an empty cache is harmless")
    func releaseMemoryOnEmptyCache() async throws {
        let rig = try await Rig.make()
        defer { rig.cleanUp() }
        let id = try await ingestWarmed(rig)

        await rig.store.database.releaseMemory()
        await rig.store.database.releaseMemory()

        #expect(await cached(rig.store.database, id, .grid) == nil)
        #expect(await rig.store.database.thumbnail(itemId: id, size: .grid) != nil)
    }

    /// OC-S5-04. Given bytes ImageIO cannot decode, when `writeThumbnails` is asked to write them, then no file is
    /// written for either size and the LRU stays empty; given a decodable image the same call writes both sizes and
    /// still leaves the LRU empty. Goes red if a failed decode writes an empty or partial file, or if the function
    /// ever stores into the memory cache.
    @Test("OC-S5-04 writeThumbnails writes nothing for undecodable bytes, files only for good ones")
    func writeThumbnailsBoundaries() async throws {
        let rig = try await Rig.make()
        defer { rig.cleanUp() }
        let db = rig.store.database
        let bad = UUID()
        let good = UUID()

        await db.writeThumbnails(itemId: bad, source: Data((0..<512).map { _ in UInt8.random(in: 0...255) }))
        await db.writeThumbnails(itemId: UUID(), source: Data())
        await db.writeThumbnails(itemId: good, source: TestImage.make(width: 100, height: 60, format: .png))

        #expect(!rig.store.exists(thumbPath(rig, bad, 256)))
        #expect(!rig.store.exists(thumbPath(rig, bad, 512)))
        #expect(rig.store.exists(thumbPath(rig, good, 256)))
        #expect(rig.store.exists(thumbPath(rig, good, 512)))
        #expect(await cached(db, good, .grid) == nil)
        #expect(await cached(db, good, .preview) == nil)
        // a 100x60 source is never upscaled
        #expect(TestImage.inspect(try Data(contentsOf: thumbPath(rig, good, 256)))?.width == 100)
    }
}
