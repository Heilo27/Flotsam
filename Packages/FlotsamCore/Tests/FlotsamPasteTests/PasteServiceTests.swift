import Foundation
import Testing
import FlotsamBase
import FlotsamStorage
@testable import FlotsamPaste

/// FR-003-15, FR-003-16, FR-003-17: the paste sequence against fakes on every port.
@MainActor
@Suite struct PasteServiceTests {
    static let target = FrontmostApp(bundleId: "com.apple.Notes", processId: 42)
    let itemId = UUID()

    struct Rig {
        let service: PasteService
        let store: FakeStore
        let pasteboard: FakePasteboard
        let ledger: OwnWriteLedger
        let frontmost: FakeFrontmost
        let keys: FakeKeys
        let host: FakeHost
        let clock: RecordingClock
    }

    private func rig(
        _ content: FlotsamResult<ItemContent>, existing: Set<String> = [], trusted: Bool = true, pollsUntilTarget: Int? = 0
    ) -> Rig {
        let store = FakeStore(content)
        let pasteboard = FakePasteboard()
        let ledger = OwnWriteLedger()
        let frontmost = FakeFrontmost(target: Self.target, pollsUntilTarget: pollsUntilTarget)
        let keys = FakeKeys()
        let host = FakeHost()
        let clock = RecordingClock()
        let service = PasteService(
            store: store, pasteboard: pasteboard, files: FakeFiles(existing: existing), frontmost: frontmost,
            accessibility: FakePermission(isAccessibilityTrusted: trusted), keys: keys, clock: clock, ownWrites: ledger)
        return Rig(service: service, store: store, pasteboard: pasteboard, ledger: ledger, frontmost: frontmost, keys: keys, host: host, clock: clock)
    }

    private func rep(_ uti: String, _ text: String = "x") -> PasteboardRepresentation {
        PasteboardRepresentation(uti: uti, data: Data(text.utf8))
    }

    private var richContent: ItemContent {
        ItemContent(kind: .richText, plainText: "hello", representations: [rep("public.rtf", "{rtf}"), rep("public.html", "<b>hello</b>")], members: [])
    }

    private func fileContent(_ paths: [String]) -> ItemContent {
        ItemContent(kind: .bundle, plainText: nil, representations: [], members: paths.map { ItemMember(path: $0, bookmark: nil, isDirectory: false) })
    }

    // MARK: Happy path

    @Test func pasteWritesEveryRepresentationThenPostsCommandV() async throws {
        let r = rig(.success(richContent))
        let outcome = try await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host).get()
        #expect(outcome == .pasted)
        #expect(r.pasteboard.written.count == 1)
        let utis = r.pasteboard.written[0].map(\.uti)
        #expect(utis.starts(with: ["public.utf8-plain-text", "public.rtf", "public.html"]))
        #expect(r.keys.posts == 1)
        #expect(r.host.hides == 1)
        #expect(r.store.recorded == [itemId])
        #expect(r.clock.slept.contains(PasteTiming.settle))
    }

    @Test func ownWriteIsMarkedAndRecordedSoCaptureSkipsIt() async throws {
        let r = rig(.success(richContent))
        _ = try await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host).get()
        let utis = r.pasteboard.written[0].map(\.uti)
        #expect(utis.contains(PasteboardMarkers.ownWrite))
        #expect(utis.contains(PasteboardMarkers.autoGenerated))
        #expect(r.ledger.contains(changeCount: r.pasteboard.changeCount))
    }

    @Test func plainTextModeWritesOnlyThePlainText() async throws {
        let r = rig(.success(richContent))
        _ = try await r.service.paste(itemId: itemId, mode: .plainText, target: Self.target, host: r.host).get()
        let utis = r.pasteboard.written[0].map(\.uti).filter { !$0.hasPrefix("org.nspasteboard") && $0 != PasteboardMarkers.ownWrite }
        #expect(utis == ["public.utf8-plain-text"])
        #expect(r.keys.posts == 1)
    }

    @Test func imageWritesItsStoredRepresentationsUntouchedEvenInPlainTextMode() async throws {
        let image = ItemContent(kind: .image, plainText: nil, representations: [rep("public.png", "png")], members: [])
        let r = rig(.success(image))
        _ = try await r.service.paste(itemId: itemId, mode: .plainText, target: Self.target, host: r.host).get()
        #expect(r.pasteboard.written[0].first == rep("public.png", "png"))
    }

    @Test func copyOnlyStopsAfterHidingThePanel() async throws {
        let r = rig(.success(richContent))
        let outcome = try await r.service.paste(itemId: itemId, mode: .copyOnly, target: Self.target, host: r.host).get()
        #expect(outcome == .copied)
        #expect(r.keys.posts == 0)
        #expect(r.host.hides == 1)
        #expect(r.store.recorded == [itemId])
        #expect(r.frontmost.polls == 0)
    }

    // MARK: Files

    @Test func fileMembersThatAreGoneAreDroppedAndTheRestPasted() async throws {
        let r = rig(.success(fileContent(["/a/one.txt", "/a/two.txt", "/a/three.txt"])), existing: ["/a/one.txt", "/a/three.txt"])
        let outcome = try await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host).get()
        #expect(outcome == .pasted)
        let files = r.pasteboard.written[0].filter { $0.uti == "public.file-url" }
        #expect(files.map { String(decoding: $0.data, as: UTF8.self) } == ["file:///a/one.txt", "file:///a/three.txt"])
    }

    @Test func everyMemberGoneIsLibDat001WithNothingWrittenAndThePanelLeftOpen() async {
        let r = rig(.success(fileContent(["/a/one.txt", "/a/two.txt"])), existing: [])
        let result = await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host)
        #expect(failureCode(result) == .libDat001)
        #expect(r.pasteboard.written.isEmpty)
        #expect(r.host.hides == 0)
        #expect(r.keys.posts == 0)
        #expect(r.store.recorded.isEmpty)
        #expect(r.store.deleted.isEmpty)
    }

    // MARK: Data missing

    @Test func missingItemDataIsLibIo001AndTheItemIsDeleted() async {
        let r = rig(.failure(FlotsamError(.libIo001, "gone")))
        let result = await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host)
        #expect(failureCode(result) == .libIo001)
        #expect(r.store.deleted == [[itemId]])
        #expect(r.pasteboard.written.isEmpty)
        #expect(r.keys.posts == 0)
    }

    @Test func aDatabaseFailureIsReportedButTheItemIsKept() async {
        let r = rig(.failure(FlotsamError(.stoDb004, "locked")))
        let result = await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host)
        #expect(failureCode(result) == .stoDb004)
        #expect(r.store.deleted.isEmpty)
    }

    @Test func aPasteboardWriteFailureStopsBeforeAnythingElse() async {
        let r = rig(.success(richContent))
        r.pasteboard.failWith = FlotsamError(.libOs001, "write refused")
        let result = await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host)
        #expect(failureCode(result) == .libOs001)
        #expect(r.store.recorded.isEmpty)
        #expect(r.host.hides == 0)
        #expect(r.keys.posts == 0)
    }

    @Test func aBookkeepingFailureDoesNotStopThePaste() async throws {
        let r = rig(.success(richContent))
        r.store.recordFailure = FlotsamError(.stoDb004, "locked")
        let outcome = try await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host).get()
        #expect(outcome == .pasted)
        #expect(r.keys.posts == 1)
    }

    // MARK: FR-003-16

    @Test func targetNeverReturningIsLibOs001WithTheItemLeftOnThePasteboard() async {
        let r = rig(.success(richContent), pollsUntilTarget: nil)
        let result = await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host)
        #expect(failureCode(result) == .libOs001)
        #expect(r.keys.posts == 0)
        #expect(r.pasteboard.written.count == 1)
        #expect(r.store.recorded == [itemId])
    }

    @Test func targetReturningWithinTheWindowStillPastes() async throws {
        let r = rig(.success(richContent), pollsUntilTarget: 10)
        let outcome = try await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host).get()
        #expect(outcome == .pasted)
        #expect(r.keys.posts == 1)
    }

    @Test func targetReturningAfterTheWindowIsTooLate() async {
        let polls = Int(PasteTiming.targetWindow / PasteTiming.pollInterval) + 2
        let r = rig(.success(richContent), pollsUntilTarget: polls)
        let result = await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host)
        #expect(failureCode(result) == .libOs001)
        #expect(r.keys.posts == 0)
    }

    @Test func noRecordedTargetIsLibOs001() async {
        let r = rig(.success(richContent))
        let result = await r.service.paste(itemId: itemId, mode: .paste, target: nil, host: r.host)
        #expect(failureCode(result) == .libOs001)
        #expect(r.keys.posts == 0)
    }

    @Test func aKeyEventThatCannotBePostedIsLibOs001WithNoRewrite() async {
        let r = rig(.success(richContent))
        r.keys.succeeds = false
        let result = await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host)
        #expect(failureCode(result) == .libOs001)
        #expect(r.pasteboard.written.count == 1)
    }

    @Test func aPanelThatNeverHidesDoesNotBlockThePasteForever() async throws {
        let r = rig(.success(richContent))
        r.host.staysVisible = true
        let outcome = try await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host).get()
        #expect(outcome == .pasted)
    }

    // MARK: FR-003-17

    @Test func accessibilityDeniedCopiesInsteadOfPasting() async throws {
        let r = rig(.success(richContent), trusted: false)
        let outcome = try await r.service.paste(itemId: itemId, mode: .paste, target: Self.target, host: r.host).get()
        #expect(outcome == .copiedAccessibilityDenied)
        #expect(r.keys.posts == 0)
        #expect(r.pasteboard.written.count == 1)
        #expect(r.host.hides == 1)
        #expect(r.store.recorded == [itemId])
    }

    @Test func accessibilityDeniedDoesNotAffectCopyOnly() async throws {
        let r = rig(.success(richContent), trusted: false)
        let outcome = try await r.service.paste(itemId: itemId, mode: .copyOnly, target: Self.target, host: r.host).get()
        #expect(outcome == .copied)
    }

    // MARK: Shared with triggers (FR-005-14)

    @Test func postPasteAloneChecksTheTargetAndPostsOnce() async throws {
        let r = rig(.success(richContent))
        try await r.service.postPaste(target: Self.target).get()
        #expect(r.keys.posts == 1)
        #expect(r.pasteboard.written.isEmpty)
    }

    /// Security F4 (TASK-345): ⌘V is addressed to the recorded target, so a focus change after the check cannot send
    /// the clip to another app.
    @Test func postPasteAddressesTheEventToTheTarget() async throws {
        let r = rig(.success(richContent))
        try await r.service.postPaste(target: Self.target).get()
        #expect(r.keys.targets == [Self.target])
    }

    @Test func aTargetThatNeverReturnsIsNeverAddressed() async {
        let r = rig(.success(richContent), pollsUntilTarget: nil)
        _ = await r.service.postPaste(target: Self.target)
        #expect(r.keys.targets.isEmpty)
    }

    private func failureCode<T>(_ result: FlotsamResult<T>) -> ErrorCode? {
        if case .failure(let error) = result { return error.code }
        return nil
    }
}
