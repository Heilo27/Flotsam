import Foundation
import Testing
import FlotsamBase
import FlotsamStorage
@testable import FlotsamPaste

// TASK-391 (Worf, blind): the Accessibility paste gate and the own-write marker list each have one home. These tests
// drive the behaviour through PasteService, ClipboardPreserver and TriggerPermissionNotice, not source text. Expected
// values are literals only. ADR-0005, FR-003-15/17, FR-005-16, FR-008-13/14.

/// A probe whose Accessibility answer a test flips mid-run, counting every question and every prompt.
private final class W391Probe: PermissionProbe, @unchecked Sendable {
    private let lock = NSLock()
    private var accessibility: Bool
    private var inputMonitoring: Bool
    private var _reads: [PermissionKind] = []
    private var _requests: [PermissionKind] = []
    private var _opened: [PermissionKind] = []
    init(accessibility: Bool, inputMonitoring: Bool = false) {
        self.accessibility = accessibility
        self.inputMonitoring = inputMonitoring
    }
    func set(accessibility value: Bool) { lock.withLock { accessibility = value } }
    var reads: [PermissionKind] { lock.withLock { _reads } }
    var requests: [PermissionKind] { lock.withLock { _requests } }
    var opened: [PermissionKind] { lock.withLock { _opened } }
    func isGranted(_ kind: PermissionKind) -> Bool {
        lock.withLock {
            _reads.append(kind)
            return kind == .accessibility ? accessibility : inputMonitoring
        }
    }
    func request(_ kind: PermissionKind) { lock.withLock { _requests.append(kind) } }
    func openSystemSettings(_ kind: PermissionKind) { lock.withLock { _opened.append(kind) } }
}

@MainActor
@Suite("TASK-391 adversarial: one gate, one marker list")
struct Worf391PasteGateAdversarialTests {
    static let target = FrontmostApp(bundleId: "com.apple.Notes", processId: 42)
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    static let ownWrite = "com.flotsam.own-write"

    private struct Rig {
        let service: PasteService
        let board: FakePasteboard
        let keys: FakeKeys
        let host = FakeHost()
    }

    private func rig(_ probe: W391Probe) -> Rig {
        let board = FakePasteboard()
        let keys = FakeKeys()
        let service = PasteService(
            store: FakeStore(.success(ItemContent(kind: .text, plainText: "hello", representations: [], members: []))),
            pasteboard: board, files: FakeFiles(existing: []),
            frontmost: FakeFrontmost(target: Self.target, pollsUntilTarget: 0),
            accessibility: probe, keys: keys, clock: RecordingClock(), ownWrites: OwnWriteLedger())
        return Rig(service: service, board: board, keys: keys)
    }

    private func rep(_ uti: String, _ text: String = "x") -> PasteboardRepresentation {
        PasteboardRepresentation(uti: uti, data: Data(text.utf8))
    }

    // MARK: the gate, through PasteService

    // OC-391-1. Red if PasteService caches the answer, or the gate stops reading the probe on each paste.
    @Test("granting and revoking Accessibility while running changes the very next paste, with no relaunch")
    func gateIsReadFreshEveryPaste() async throws {
        let probe = W391Probe(accessibility: false)
        let r = rig(probe)
        let first = try await r.service.paste(itemId: UUID(), mode: .paste, target: Self.target, host: r.host).get()
        #expect(first == .copiedAccessibilityDenied)
        #expect(r.keys.posts == 0)

        probe.set(accessibility: true)
        let second = try await r.service.paste(itemId: UUID(), mode: .paste, target: Self.target, host: FakeHost()).get()
        #expect(second == .pasted)
        #expect(r.keys.posts == 1)

        probe.set(accessibility: false)
        let third = try await r.service.paste(itemId: UUID(), mode: .paste, target: Self.target, host: FakeHost()).get()
        #expect(third == .copiedAccessibilityDenied)
        #expect(r.keys.posts == 1, "a revoked permission must not post a third keystroke")
        #expect(r.board.written.count == 3, "every attempt still copies, granted or not")
    }

    // OC-391-2. Red if the denied branch skips the plain-text mode, or the gate is bypassed by a mode.
    @Test("negative: denied Accessibility blocks the keystroke in .paste and .plainText alike; the item is still copied")
    func deniedBlocksEveryKeystrokeMode() async throws {
        for mode in [PasteMode.paste, .plainText] {
            let r = rig(W391Probe(accessibility: false))
            let outcome = try await r.service.paste(itemId: UUID(), mode: mode, target: Self.target, host: r.host).get()
            #expect(outcome == .copiedAccessibilityDenied)
            #expect(r.keys.posts == 0)
            #expect(r.board.written.count == 1)
        }
    }

    // OC-391-3. Red if the gate check moves ahead of the copy-only guard (copy-only never needs, nor asks for, Accessibility).
    @Test("boundary: copy-only with Accessibility granted posts nothing; with it denied does not prompt or report denial")
    func copyOnlyNeverTouchesTheGate() async throws {
        let granted = W391Probe(accessibility: true)
        let a = rig(granted)
        #expect(try await a.service.paste(itemId: UUID(), mode: .copyOnly, target: Self.target, host: a.host).get() == .copied)
        #expect(a.keys.posts == 0)

        let denied = W391Probe(accessibility: false)
        let b = rig(denied)
        #expect(try await b.service.paste(itemId: UUID(), mode: .copyOnly, target: Self.target, host: b.host).get() == .copied)
        #expect(denied.requests.isEmpty, "⇧Return must not raise the Accessibility prompt")
        #expect(denied.reads.isEmpty, "⇧Return must not even ask the gate")
    }

    // OC-391-4. Red if a second denial prompts again, or the first denial never prompts (FR-008-13).
    @Test("the first denied paste prompts for Accessibility exactly once; the second does not")
    func promptsOnce() async throws {
        let probe = W391Probe(accessibility: false)
        let r = rig(probe)
        _ = try await r.service.paste(itemId: UUID(), mode: .paste, target: Self.target, host: r.host).get()
        _ = try await r.service.paste(itemId: UUID(), mode: .paste, target: Self.target, host: FakeHost()).get()
        #expect(probe.requests == [.accessibility])
        #expect(probe.opened.isEmpty)
    }

    // OC-391-5. Red if the gate consults Input Monitoring (or anything but Accessibility).
    @Test("Accessibility alone decides: all four permission combinations")
    func gateMatrix() {
        let cases: [(ax: Bool, im: Bool, allowed: Bool)] = [
            (true, true, true), (true, false, true), (false, true, false), (false, false, false),
        ]
        for c in cases {
            let probe = W391Probe(accessibility: c.ax, inputMonitoring: c.im)
            #expect(PasteGate.isAllowed(probe: probe) == c.allowed, "ax=\(c.ax) im=\(c.im)")
            #expect(probe.isAccessibilityTrusted == c.allowed, "footer disagrees with the gate: ax=\(c.ax) im=\(c.im)")
        }
        let probe = W391Probe(accessibility: true)
        _ = PasteGate.isAllowed(probe: probe)
        #expect(probe.reads == [.accessibility], "one question per decision, and only about Accessibility")
        #expect(probe.requests.isEmpty && probe.opened.isEmpty, "reading the gate never prompts")
    }

    // OC-391-6. Red if the Triggers pane notice stops using the gate's error code, or reorders/omits a code.
    @Test("Triggers pane notice: SET-PRM-001 then SET-PRM-002, each only when its permission is off, none when triggers are off")
    func noticeMatrix() {
        func codes(_ ax: Bool, _ im: Bool, enabled: Bool = true) -> [String] {
            TriggerPermissionNotice.missing(triggersEnabled: enabled, probe: W391Probe(accessibility: ax, inputMonitoring: im))
                .map(\.rawValue)
        }
        #expect(codes(false, false) == ["SET-PRM-001", "SET-PRM-002"])
        #expect(codes(false, true) == ["SET-PRM-001"])
        #expect(codes(true, false) == ["SET-PRM-002"])
        #expect(codes(true, true) == [])
        #expect(codes(false, false, enabled: false) == [])
    }

    // OC-391-7. Red if copyOnlyError loses its code, text, or the itemId context.
    @Test("the copy-only error is SET-PRM-001 with its exact text, and carries the item id only when given")
    func copyOnlyErrorShape() {
        let id = UUID()
        let plain = PasteGate.copyOnlyError()
        #expect(plain.code == .setPrm001)
        #expect("\(plain.internalMessage)" == "Accessibility not granted; pasting by copy only")
        #expect(plain.context.isEmpty)
        let withItem = PasteGate.copyOnlyError(itemId: id)
        #expect(withItem.code == .setPrm001)
        #expect(withItem.context.count == 1)
        #expect(withItem.context[.itemId] == .id(id))
    }

    // MARK: the own-write marker list

    // OC-391-8. Red if a writer drops a marker, reorders them, or writes them twice.
    @Test("every Flotsam write ends with exactly AutoGeneratedType then own-write, once each, after the content")
    func writeCarriesBothMarkersOnce() async throws {
        let r = rig(W391Probe(accessibility: true))
        _ = try await r.service.paste(itemId: UUID(), mode: .paste, target: Self.target, host: r.host).get()
        let written = try #require(r.board.written.last).map(\.uti)
        #expect(written.suffix(2) == [Self.autoGenerated, Self.ownWrite])
        #expect(written.filter { $0 == Self.autoGenerated }.count == 1)
        #expect(written.filter { $0 == Self.ownWrite }.count == 1)
        #expect(written.first == "public.utf8-plain-text")
        #expect(try #require(r.board.written.last).suffix(2).allSatisfy { $0.data.isEmpty }, "markers carry no data")
    }

    // OC-391-9. Red if the restore filter forgets a marker (it would be written twice) or drops a real type.
    @Test("restore: held copy drops both markers and dedupes, keeps real types; the write re-adds each marker exactly once")
    func preserverFiltersAndReaddsMarkers() async throws {
        let board = ScriptedPasteboard([
            rep("public.png", "img"), rep(Self.autoGenerated, ""), rep(Self.ownWrite, ""),
            rep(PasteboardUTI.plainText, "first"), rep(PasteboardUTI.plainText, "second"),
        ])
        let ledger = OwnWriteLedger()
        let preserver = ClipboardPreserver(pasteboard: board, ownWrites: ledger, clock: RecordingClock())
        let held = preserver.capture()
        #expect(held.disposition == .held)
        #expect(held.representations.map(\.uti) == ["public.png", PasteboardUTI.plainText])
        #expect(held.representations.last.map { String(decoding: $0.data, as: UTF8.self) } == "first")

        let outcome = await preserver.restore(held, writeChangeCount: board.changeCount)
        #expect(outcome == .restored)
        let restored = try #require(board.writes.last).map(\.uti)
        #expect(restored == ["public.png", PasteboardUTI.plainText, Self.autoGenerated, Self.ownWrite])
        #expect(board.writes.count == 1)
    }

    // OC-391-10. Red if the refactor disturbed Concealed/Transient handling: a marked secret is never held.
    @Test("negative: Concealed or Transient pasteboards are never held, even when Flotsam's own markers are present")
    func concealedAndTransientStayRefused() {
        for secret in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType"] {
            let board = ScriptedPasteboard([rep(PasteboardUTI.plainText, "hunter2"), rep(secret, ""), rep(Self.ownWrite, "")])
            let held = ClipboardPreserver(pasteboard: board, ownWrites: OwnWriteLedger(), clock: RecordingClock()).capture()
            #expect(held.disposition == .concealed, Comment(rawValue: secret))
            #expect(held.plainText.isEmpty)
            #expect(held.representations.isEmpty)
        }
        #expect(PasteboardMarkers.neverStore == [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        ])
    }

    // OC-391-11. Red if the ledger stops recognising a change it wrote through the shared list.
    @Test("the ledger recognises its own write's changeCount, and not another app's next one")
    func ledgerRecognisesOwnWriteOnly() throws {
        let board = FakePasteboard()
        let ledger = OwnWriteLedger()
        let count = try ledger.write([rep(PasteboardUTI.plainText)], to: board).get()
        #expect(count == 1)
        #expect(ledger.contains(changeCount: 1))
        #expect(!ledger.contains(changeCount: 2))
    }
}
