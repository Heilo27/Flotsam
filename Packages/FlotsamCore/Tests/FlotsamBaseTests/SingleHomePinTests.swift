@testable import FlotsamBase

// TASK-391 (Rule 9): one home for the Accessibility paste gate and for the own-write pasteboard types. These pin the
// homes so a second copy of either rule fails here instead of drifting quietly (ADR-0005).

/// Repo root, found by walking up from this file to `project.yml`.
private func repoRoot() -> URL? {
    var url = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    for _ in 0..<12 {
        if FileManager.default.fileExists(atPath: url.appendingPathComponent("project.yml").path) { return url }
        url.deleteLastPathComponent()
    }
    return nil
}

/// Every `.swift` file under `relativePath` (relative to the repo root) as (path relative to the root, text).
private func swiftSources(under relativePath: String) -> [(path: String, text: String)] {
    guard let root = repoRoot() else { return [] }
    let base = root.appendingPathComponent(relativePath)
    var found: [(String, String)] = []
    let files = FileManager.default.enumerator(at: base, includingPropertiesForKeys: nil)
    while let url = files?.nextObject() as? URL {
        guard url.pathExtension == "swift", let text = try? String(contentsOf: url, encoding: .utf8) else { continue }
        found.append((String(url.path.dropFirst(root.path.count + 1)), text))
    }
    return found
}

private struct GateProbe: PermissionProbe {
    let accessibility: Bool
    func isGranted(_ kind: PermissionKind) -> Bool { kind == .accessibility ? accessibility : false }
    func request(_ kind: PermissionKind) {}
    func openSystemSettings(_ kind: PermissionKind) {}
}

@Suite("TASK-391 single homes (Rule 9)")
struct SingleHomePinTests {
    private static let production = ["Packages/FlotsamCore/Sources", "App"]

    // MARK: Accessibility gate

    @Test("the footer's Accessibility question and the paste decision are the same answer")
    func footerAndGateAgree() {
        for granted in [true, false] {
            let probe = GateProbe(accessibility: granted)
            #expect(probe.isAccessibilityTrusted == PasteGate.isAllowed(probe: probe))
            #expect(PasteGate.isAllowed(probe: probe) == granted)
        }
    }

    @Test("PasteGateOutcome is gone: the gate decides, PasteOutcome is the only paste result type")
    func noSecondOutcomeType() {
        for (path, text) in Self.production.flatMap(swiftSources(under:)) {
            #expect(!text.contains("PasteGateOutcome"), "\(path) names the retired PasteGateOutcome")
        }
        let own = swiftSources(under: "Packages/FlotsamCore/Sources").filter { $0.text.contains("enum PasteOutcome") }
        #expect(own.map(\.path) == ["Packages/FlotsamCore/Sources/FlotsamPaste/PasteTypes.swift"])
    }

    @Test("only PasteGate tests the Accessibility permission, and PasteService and TriggerExpander both ask it")
    func gateIsTheOnlyAccessibilityTest() throws {
        let sources = swiftSources(under: "Packages/FlotsamCore/Sources")
        let readers = sources.filter { $0.text.contains("isGranted(.accessibility)") }.map(\.path)
        #expect(readers == ["Packages/FlotsamCore/Sources/FlotsamBase/Settings/Permissions.swift"])
        for name in ["FlotsamPaste/PasteService.swift", "FlotsamTriggers/TriggerExpander.swift"] {
            let text = try #require(sources.first { $0.path.hasSuffix(name) }?.text)
            #expect(text.contains("PasteGate.isAllowed(probe:"), "\(name) must ask PasteGate")
        }
    }

    // MARK: Own-write types

    @Test("the own-write marker list is exactly AutoGeneratedType then com.flotsam.own-write")
    func ownWriteTypesLiteral() {
        #expect(PasteboardMarkers.ownWriteTypes == ["org.nspasteboard.AutoGeneratedType", "com.flotsam.own-write"])
    }

    @MainActor
    @Test("the ledger and Copy Diagnostics put the same marker types on the pasteboard")
    func ledgerAndDiagnosticsWriteTheSameMarkers() throws {
        let viaLedger = FakePasteboard()
        let text = PasteboardRepresentation(uti: PasteboardUTI.plainText, data: Data("x".utf8))
        _ = OwnWriteLedger().write([text], to: viaLedger)
        let ledgerMarkers = try #require(viaLedger.written.first).dropFirst().map(\.uti)

        let viaDiagnostics = FakePasteboard()
        _ = DiagnosticsCopier(pasteboard: viaDiagnostics, ownWriteTypes: PasteboardMarkers.ownWriteTypes).copy("x")
        let diagnosticsMarkers = try #require(viaDiagnostics.written.first).dropFirst().map(\.uti)

        #expect(ledgerMarkers == PasteboardMarkers.ownWriteTypes)
        #expect(diagnosticsMarkers == ledgerMarkers)
    }

    @Test("the marker spellings are written once; Settings diagnostics reads the shared list")
    func markerSpellingsHaveOneHome() throws {
        let home = "Packages/FlotsamCore/Sources/FlotsamBase/Pasteboard/OwnWriteLedger.swift"
        for (path, text) in Self.production.flatMap(swiftSources(under:)) where path != home {
            #expect(!text.contains("com.flotsam.own-write"), "\(path) spells the own-write type itself")
            #expect(!text.contains("AutoGeneratedType"), "\(path) spells the auto-generated type itself")
        }
        let diagnostics = try #require(
            swiftSources(under: "App/Flotsam/Settings").first { $0.path.hasSuffix("SettingsDiagnostics.swift") }?.text)
        #expect(diagnostics.contains("PasteboardMarkers.ownWriteTypes"))
    }
}
