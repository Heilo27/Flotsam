// TASK-504 (Worf), OC-3113 (capture half), FR-003-23 / AC-003-19 with FR-001-03: a secure item re-copied by Flotsam
// after the owner check is skipped by capture as an own write (CAP-POL-004) and adds nothing. The Library half
// (what the re-copy writes, and that {clipboard} reads empty) is in FlotsamLibraryTests/Frd003ContractSecureTests.
// Collaborators are real (SecureClipVault over a fake Keychain, ClipboardCapture, IngestWorker, IngestActor, an
// on-disk FlotsamDatabase, OwnWriteLedger); the pasteboard, clock, source lookup and log sink are the contract fakes.
// Expected values are literals.

private final class RecopyKeychain: SecureKeyStore, @unchecked Sendable {
    private let lock = NSLock()
    private var stored: Data?
    func readKey() -> FlotsamResult<Data?> { lock.withLock { .success(stored) } }
    func storeKeyIfAbsent(_ key: Data) -> FlotsamResult<Data> {
        lock.withLock {
            if stored == nil { stored = key }
            return .success(stored!)
        }
    }
}

@MainActor
private final class RecopyRig {
    static let secret = "hunter2-secret"
    let root: URL
    let database: FlotsamDatabase
    let pasteboard = ContractPasteboard()
    let ledger = OwnWriteLedger()
    let sink = RecordingSink()
    let capture: ClipboardCapture
    let reporter: ErrorReporter
    private var started = false

    init() async throws {
        root = FileManager.default.temporaryDirectory.appendingPathComponent("flotsam-504-capture-\(UUID().uuidString)")
        let vault = SecureClipVault(store: RecopyKeychain())
        database = try await FlotsamDatabase.open(folder: root.appendingPathComponent("data"), secureVault: vault).get()
        let settings = SettingsStore(store: ContractKV())
        reporter = ErrorReporter(presenter: FRD001RecordingPresenter(), clock: ManualClock(), sink: sink)
        capture = ClipboardCapture(
            pasteboard: pasteboard, sourceApps: ContractSourceApps(frontmost: ContractRig.writerApp), ownWrites: ledger,
            ingest: IngestActor(database: database, settings: settings), settings: settings, reporter: reporter,
            ignoredApps: { [] }, access: AllowedPasteboardAccess(), vault: vault, clock: ManualClock(), sink: sink,
            scheduleTimer: inertTimer)
    }

    func finish() async {
        await capture.stop()
        try? FileManager.default.removeItem(at: root)
    }

    /// Runs one capture over whatever the pasteboard now holds.
    func process() async {
        if !started {
            capture.start()
            started = true
        }
        capture.captureNow()
        await capture.stop()
        capture.start()
        await quiesceReporter(reporter)
    }

    /// A password manager's copy: plain text and ConcealedType, nothing of Flotsam's.
    func copyFromPasswordManager() async {
        pasteboard.copy([
            PasteboardRepresentation(uti: "public.utf8-plain-text", data: Data(Self.secret.utf8)),
            PasteboardRepresentation(uti: "org.nspasteboard.ConcealedType", data: Data()),
        ])
        await process()
    }

    func itemCount() async throws -> Int {
        try await database.pool.read { try Int.fetchOne($0, sql: "SELECT COUNT(*) FROM item")! }
    }

    func copyCount() async throws -> Int? {
        try await database.pool.read { try Int.fetchOne($0, sql: "SELECT copyCount FROM item WHERE isSecure = 1") }
    }
}

@MainActor
@Suite struct Frd003ContractSecureRecopyTests {
    private static let revealedTypes = [
        "com.flotsam.own-write", "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.ConcealedType",
        "public.utf8-plain-text",
    ]

    private func expectSkippedAsOwnWrite(_ rig: RecopyRig, sourceLocation: SourceLocation = #_sourceLocation) {
        #expect(rig.sink.logged(.capPol004).count == 1, "exactly one CAP-POL-004 record", sourceLocation: sourceLocation)
        #expect(rig.sink.logged(.capPol004).map(\.level) == [.info], "CAP-POL-004 logs at info", sourceLocation: sourceLocation)
        // not CAP-POL-001: the AutoGenerated type alone would reject it as a policy skip if the own-write guard were gone
        #expect(rig.sink.logged(.capPol001).isEmpty, "the skip is the own-write guard, not the auto-generated type", sourceLocation: sourceLocation)
    }

    // Red if the re-copy is captured (copyCount becomes 2 or a second row appears), if the own-write guard is removed
    // (the skip then logs CAP-POL-001 or nothing), or if the re-copy stops carrying the own-write markers.
    @Test("OC-3113 AC-003-19 FR-001-03: Flotsam's own re-copy of a secure item adds nothing and is skipped as CAP-POL-004")
    func ownRecopyIsSkipped() async throws {
        // given a secure item captured from a password manager (N = 1, copyCount 1)
        let rig = try await RecopyRig()
        await rig.copyFromPasswordManager()
        #expect(try await rig.itemCount() == 1)
        #expect(try await rig.copyCount() == 1)
        rig.sink.reset()

        // when Flotsam re-copies it through the ledger, the way PasteService does after the owner check
        _ = rig.ledger.write(SecureClip.pasteboardRepresentations(revealing: RecopyRig.secret), to: rig.pasteboard)
        #expect(rig.pasteboard.currentTypeIdentifiers().sorted() == Self.revealedTypes)
        await rig.process()

        // then no new item, the copy count is unchanged, and capture skipped it as an own write
        #expect(try await rig.itemCount() == 1)
        #expect(try await rig.copyCount() == 1)
        expectSkippedAsOwnWrite(rig)
        await rig.finish()
    }

    // Red if the marker guard is removed from capture: a re-copy by a second Flotsam process (not in this ledger) would
    // then be captured or rejected for the wrong reason (CAP-POL-001 from the AutoGenerated type).
    @Test("OC-3113 AC-003-19 FR-001-03: the own-write marker alone is enough (a change not in the ledger)")
    func ownWriteMarkerAloneSkips() async throws {
        // given a secure item, and a pasteboard change with the four re-copy types that was never recorded in the ledger
        let rig = try await RecopyRig()
        await rig.copyFromPasswordManager()
        rig.sink.reset()
        rig.pasteboard.copy(Self.revealedTypes.map { PasteboardRepresentation(uti: $0, data: $0 == "public.utf8-plain-text" ? Data(RecopyRig.secret.utf8) : Data()) })

        // when capture runs
        await rig.process()

        // then nothing is added or bumped and the skip is CAP-POL-004
        #expect(try await rig.itemCount() == 1)
        #expect(try await rig.copyCount() == 1)
        expectSkippedAsOwnWrite(rig)
        await rig.finish()
    }

    // Control: the same password copied again by the password manager (no own-write marker) IS captured and bumps the one
    // row, so the two tests above skipped because of the own-write marking and not because capture ignores secure items.
    @Test("OC-3113 AC-003-19 FR-001-15: a genuine second copy of the same password bumps the one secure row")
    func genuineSecondCopyIsCaptured() async throws {
        // given a secure item captured once
        let rig = try await RecopyRig()
        await rig.copyFromPasswordManager()
        rig.sink.reset()

        // when the password manager copies the same password again
        await rig.copyFromPasswordManager()

        // then still one row, copy count 2, and no own-write skip
        #expect(try await rig.itemCount() == 1)
        #expect(try await rig.copyCount() == 2)
        #expect(rig.sink.logged(.capPol004).isEmpty)
        await rig.finish()
    }
}
