        }
    }

    @Test("OC-1016: an ignored frontmost app's copy is dropped with CAP-POL-002; the next app's copy is stored")
    func oc1016() async throws {
        // given app X ignored; when X copies G1 then app Y copies G2; then only G2 stored, delta +1.
        try await withRig(frontmost: SourceApp(bundleId: "com.example.ignored", name: "Ignored")) { rig in
            rig.ignored = ["com.example.ignored"]
            let g1 = uid("G1"), g2 = uid("G2")
            rig.pasteboard.copyText(g1)
            await rig.process()
            try #expect(await rig.itemCount() == 0)
            #expect(rig.sink.logged(.capPol002).count == 1)

            rig.sourceApps.frontmost = SourceApp(bundleId: "com.example.other", name: "Other")
            rig.pasteboard.copyText(g2)
            await rig.process()
            let stored = try await rig.items()
            #expect(stored.count == 1)
            #expect(stored.first?.plainText == g2)
            #expect(rig.sink.logged(.capPol002).count == 1)
        }
    }

    @Test("OC-1017: paused capture drops a copy with CAP-POL-003 and resuming does not resurrect it")
    func oc1017() async throws {
        // given Paused; when P is copied, capture resumes, then R is copied; then only R stored.
        try await withRig { rig in
            rig.settings.set(.paused, for: SettingKeys.captureMode)
            let p = uid("P"), r = uid("R")
            rig.pasteboard.copyText(p)
            await rig.process()
            try #expect(await rig.itemCount() == 0)
            #expect(rig.sink.logged(.capPol003).count == 1)

            rig.settings.set(.active, for: SettingKeys.captureMode)
            await rig.process()
            try #expect(await rig.item(withText: p).isEmpty)

            rig.pasteboard.copyText(r)
            await rig.process()
            let stored = try await rig.items()
            #expect(stored.count == 1)
            #expect(stored.first?.plainText == r)
        }
    }

