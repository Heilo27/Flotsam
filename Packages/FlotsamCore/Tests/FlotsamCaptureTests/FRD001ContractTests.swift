@MainActor
@Suite("FRD-001 contract: gates and write path")
struct FRD001GateContractTests {

    @Test("OC-1002: an untouched pasteboard logs no processed entry and stores nothing")
    func oc1002() async throws {
        // given Active mode, nothing copied; when several ticks pass; then no records and count unchanged.
        try await withRig { rig in
            for _ in 0..<5 { await rig.process() }
            #expect(rig.sink.records.filter { $0.headline == "pasteboard.processed" }.isEmpty)
            try #expect(await rig.itemCount() == 0)
            #expect(rig.pasteboard.snapshotReads == 0)
        }
    }

    @Test("OC-1004: text already on the pasteboard at launch is captured with no further copy")
    func oc1004() async throws {
        // given a pasteboard holding L before capture starts; when capture starts; then one item with text L.
        try await withRig(startCapture: false) { rig in
            let text = uid("launch")
            rig.pasteboard.copyText(text)
            try #expect(await rig.itemCount() == 0)
            rig.capture.start()
            await rig.process()
            let stored = try await rig.items()
            #expect(stored.count == 1)
            #expect(stored.first?.plainText == text)
        }
    }

    @Test("OC-1005: an immediate check right after the copy stores it without waiting for a timer tick")
    func oc1005() async throws {
        // given a fresh copy W; when captureNow runs (what an app-activation hook calls); then W is stored.
        try await withRig { rig in
            let text = uid("W")
            rig.pasteboard.copyText(text)
            rig.capture.captureNow()
            #expect(await rig.until { try await rig.itemCount() == 1 })
            try #expect(await rig.items().map(\.plainText) == [text])
        }
    }

    @Test("OC-1006: repeated immediate checks of the same change store exactly one item with copy count 1")
    func oc1006() async throws {
        // given unique text I; when captureNow fires five times for the one change; then count +1 and copyCount 1.
        try await withRig { rig in
            let text = uid("I")
            rig.pasteboard.copyText(text)
            for _ in 0..<5 { rig.capture.captureNow() }
            await rig.process()
            let stored = try await rig.items()
            #expect(stored.count == 1)
            #expect(stored.first?.plainText == text)
            #expect(stored.first?.copyCount == 1)
            #expect(rig.pasteboard.snapshotReads == 1)
        }
    }

    @Test("OC-1008: a Flotsam write carries AutoGenerated and own-write markers (reachable half of paste-back)")
    func oc1008() async throws {
        // given the ledger writes item P back; then the pasteboard types include both markers.
        try await withRig { rig in
            _ = rig.ledger.write([PasteboardRepresentation(uti: PB.text, data: PB.data("P"))], to: rig.pasteboard)
            let types = rig.pasteboard.currentTypeIdentifiers()
            #expect(types.contains("org.nspasteboard.AutoGeneratedType"))
            #expect(types.contains("com.flotsam.own-write"))
            #expect(types.contains(PB.text))
        }
    }

    @Test("OC-1009: pasting an item back stores nothing, keeps copy count, logs CAP-POL-004")
    func oc1009() async throws {
        // given item P with copyCount 1; when the ledger writes P back; then count 1, copyCount 1, one POL-004.
        try await withRig { rig in
            let text = uid("P")
            await rig.copyText(text)
            let before = try await rig.items()
            #expect(before.count == 1)
            #expect(before.first?.copyCount == 1)

            _ = rig.ledger.write([PasteboardRepresentation(uti: PB.text, data: PB.data(text))], to: rig.pasteboard)
            await rig.process()

            let after = try await rig.items()
            #expect(after.count == 1)
            #expect(after.first?.id == before.first?.id)
            #expect(after.first?.copyCount == 1)
            #expect(rig.sink.logged(.capPol004).count == 1)
            #expect(rig.sink.logged(.capPol001).isEmpty)
        }
    }

    @Test("OC-1010: two further own writes each log CAP-POL-004 and add no item")
    func oc1010() async throws {
        // given the ledger writing twice (copy-only and diagnostics write paths); then 0 items and two POL-004.
        try await withRig { rig in
            _ = rig.ledger.write([PasteboardRepresentation(uti: PB.text, data: PB.data("copy-only"))], to: rig.pasteboard)
            await rig.process()
