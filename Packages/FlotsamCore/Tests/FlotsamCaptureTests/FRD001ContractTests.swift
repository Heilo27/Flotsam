            _ = rig.ledger.write([PasteboardRepresentation(uti: PB.text, data: PB.data("diagnostics"))], to: rig.pasteboard)
            await rig.process()
            #expect(rig.sink.logged(.capPol004).count == 2)
            try #expect(await rig.itemCount() == 0)
        }
    }

    @Test("OC-1011: a third party text with the own-write type is not stored and logs CAP-POL-004")
    func oc1011() async throws {
        // given text Z plus com.flotsam.own-write written outside the ledger; then count 0, one POL-004, no bytes read.
        try await withRig { rig in
            rig.pasteboard.copy([(PB.text, PB.data("Z")), (PasteboardMarkers.ownWrite, Data())])
            await rig.process()
            try #expect(await rig.itemCount() == 0)
            #expect(rig.sink.logged(.capPol004).count == 1)
            #expect(rig.pasteboard.bytesRequested.isEmpty)
        }
    }

    private func neverStore(_ marker: String, label: String) async throws {
        try await withRig { rig in
            let secret = "secret-marker-\(label)-\(UUID().uuidString)"
            rig.pasteboard.copy([(PB.text, PB.data(secret)), (marker, Data("1".utf8))])
            await rig.process()
            try #expect(await rig.itemCount() == 0)
            try #expect(await rig.searchCount("secret-marker-\(label)") == 0)
            #expect(rig.sink.logged(.capPol001).count == 1)
            #expect(rig.sink.logged(.capPol002).isEmpty && rig.sink.logged(.capPol003).isEmpty)
            #expect(!rig.sink.everything.contains(secret))
            #expect(!rig.sink.everything.contains("secret-marker"))
            #expect(rig.pasteboard.bytesRequested.isEmpty)
        }
    }

    @Test("OC-1012: ConcealedType text is rejected with CAP-POL-001 and never appears in logs")
    func oc1012() async throws { try await neverStore(PasteboardMarkers.concealed, label: "Concealed") }

    @Test("OC-1013: TransientType text is rejected with CAP-POL-001 and never appears in logs")
    func oc1013() async throws { try await neverStore(PasteboardMarkers.transient, label: "Transient") }

    @Test("OC-1014: AutoGeneratedType text is rejected with CAP-POL-001 and never appears in logs")
