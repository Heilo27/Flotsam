import Foundation
import Testing
import FlotsamBase
@testable import FlotsamStorage
@testable import FlotsamCapture

/// FR-005-06 Save Clipboard, through the real `ClipboardCapture.saveClipboardNow` and its collaborators (classifier,
/// ingest actor, a real database). Only the pasteboard, source-app lookup, key-value store and presenter are fakes.
/// Persistence is read back through a FRESH database instance (`GapRig.freshRows`), never an in-memory array.
@MainActor
@Suite("FR-005-06 worf: Save Clipboard", .serialized, .timeLimit(.minutes(2)))
struct SaveClipboardWorfTests {
    private func rig(mode: CaptureMode) async throws -> GapRig {
        let rig = try await GapRig()
        rig.settings.set(mode, for: SettingKeys.captureMode)
        return rig
    }

    // MARK: AC-005-06 saves in Curated and Paused

    /// OC-WSC-001. given Curated mode and text copied, when the poll runs then Save Clipboard runs, then the poll alone
    /// stored nothing, the save returns `.saved` and exactly one item with that text exists in a fresh database.
    /// Red if `saveClipboardNow` stops committing, or if Curated starts auto-saving (the poll count would be 1).
    @Test("OC-WSC-001 Curated: poll holds the copy, Save Clipboard commits exactly one item")
    func curatedSaves() async throws {
        let rig = try await rig(mode: .curated); defer { Task { await rig.cleanUp() } }
        rig.capture.start()
        rig.text("curated clip")
        await rig.settle()
        #expect(await rig.itemCount() == 0)

        let outcome = await rig.capture.saveClipboardNow()

        #expect(outcome == .saved)
        let rows = try await rig.freshRows()
        #expect(rows.count == 1)
        #expect(rows.first?.plainText == "curated clip")
        #expect(rows.first?.copyCount == 1)
    }

    /// OC-WSC-002. given Paused mode and text copied, when Save Clipboard runs, then it saves one item even though gate
    /// 1 rejects every poll. Red if `saveClipboardNow` consults the capture mode.
    @Test("OC-WSC-002 Paused: Save Clipboard still saves exactly one item")
    func pausedSaves() async throws {
        let rig = try await rig(mode: .paused); defer { Task { await rig.cleanUp() } }
        rig.text("paused clip")

        let outcome = await rig.capture.saveClipboardNow()

        #expect(outcome == .saved)
        let rows = try await rig.freshRows()
        #expect(rows.map(\.plainText) == ["paused clip"])
    }

    // MARK: AC-005-06 rejections

    /// OC-WSC-003. given Concealed content (and, separately, Transient and AutoGenerated), when Save Clipboard runs, then
    /// `.rejected(CAP-POL-001)`, zero rows, and the text bytes were never read. Red if `saveClipboardNow` bypasses the
    /// neverStore gate or maps it to a different code.
    @Test("OC-WSC-003 Concealed, Transient and AutoGenerated are never saved and reject with CAP-POL-001",
          arguments: [PasteboardMarkers.concealed, PasteboardMarkers.transient, PasteboardMarkers.autoGenerated])
    func privateMarkersAreRejected(marker: String) async throws {
        let rig = try await rig(mode: .curated); defer { Task { await rig.cleanUp() } }
        rig.text("hunter2", markers: [marker])

        let outcome = await rig.capture.saveClipboardNow()

        guard case .rejected(let error) = outcome else { Issue.record("expected a rejection, got \(outcome)"); return }
        #expect(error.code == .capPol001)
        #expect(await rig.itemCount() == 0)
        #expect(!rig.pasteboard.bytesRequested.contains(GapRig.textType))
    }

    /// OC-WSC-004. given the frontmost app is on the ignored list, when Save Clipboard runs, then `.rejected(CAP-POL-002)`
    /// and zero rows. Red if the ignored-app gate is skipped on the save path.
    @Test("OC-WSC-004 an ignored source app rejects with CAP-POL-002")
    func ignoredAppIsRejected() async throws {
        let rig = try await rig(mode: .curated); defer { Task { await rig.cleanUp() } }
        rig.ignored.value = [GapRig.frontmostBundle]
        rig.text("from an ignored app")

        let outcome = await rig.capture.saveClipboardNow()

        guard case .rejected(let error) = outcome else { Issue.record("expected a rejection, got \(outcome)"); return }
        #expect(error.code == .capPol002)
        #expect(await rig.itemCount() == 0)
    }

    /// OC-WSC-005. given a pasteboard with no types, when Save Clipboard runs, then `.rejected(CAP-VAL-001)` at once (no
    /// reread: nothing will tick for a user action) and zero rows. Red if the save path rereads (silent, no rejection)
    /// or reports nothing.
    @Test("OC-WSC-005 an empty pasteboard rejects at once with CAP-VAL-001")
    func emptyPasteboardIsRejectedAtOnce() async throws {
        let rig = try await rig(mode: .curated); defer { Task { await rig.cleanUp() } }
        rig.pasteboard.copy([:])

        let outcome = await rig.capture.saveClipboardNow()

        guard case .rejected(let error) = outcome else { Issue.record("expected a rejection, got \(outcome)"); return }
        #expect(error.code == .capVal001)
        #expect(await rig.itemCount() == 0)
    }

    /// OC-WSC-006. given types the app does not honour, when Save Clipboard runs, then `.rejected(CAP-VAL-001)`.
    /// Red if gate 5 is skipped on the save path.
    @Test("OC-WSC-006 a pasteboard with no honoured type rejects with CAP-VAL-001")
    func unhonouredTypeIsRejected() async throws {
        let rig = try await rig(mode: .curated); defer { Task { await rig.cleanUp() } }
        rig.pasteboard.copy(["com.example.opaque": Data([1, 2, 3])])

        let outcome = await rig.capture.saveClipboardNow()

        guard case .rejected(let error) = outcome else { Issue.record("expected a rejection, got \(outcome)"); return }
        #expect(error.code == .capVal001)
        #expect(await rig.itemCount() == 0)
    }

    /// OC-WSC-007. given the pasteboard holds the app's own write, when Save Clipboard runs, then `.rejected(CAP-POL-004)`
    /// and zero rows (gate 2). Red if the own-write check is dropped from the save path.
    @Test("OC-WSC-007 the app's own write is not saved")
    func ownWriteIsRejected() async throws {
        let rig = try await rig(mode: .curated); defer { Task { await rig.cleanUp() } }
        _ = rig.ledger.write([PasteboardRepresentation(uti: GapRig.textType, data: Data("own".utf8))], to: rig.pasteboard)

        let outcome = await rig.capture.saveClipboardNow()

        guard case .rejected(let error) = outcome else { Issue.record("expected a rejection, got \(outcome)"); return }
        #expect(error.code == .capPol004)
        #expect(await rig.itemCount() == 0)
    }

    /// OC-WSC-008. boundary: text of exactly the 10 MiB ceiling saves; one byte more rejects with `CAP-LIM-001` and
    /// stores nothing, and the rejection is returned, not also raised as a Notice (FR-005-06 "never also a Notice").
    /// Red if the ceiling moves, the code changes, or the save path reports the failure as a Notice too.
    @Test("OC-WSC-008 text at the ceiling saves; one byte over rejects with CAP-LIM-001 and no Notice")
    func ceilingBoundary() async throws {
        let rig = try await rig(mode: .curated); defer { Task { await rig.cleanUp() } }
        rig.text(String(repeating: "a", count: 10 * 1024 * 1024))
        #expect(await rig.capture.saveClipboardNow() == .saved)
        #expect(await rig.itemCount() == 1)

        rig.text(String(repeating: "b", count: 10 * 1024 * 1024 + 1))
        let outcome = await rig.capture.saveClipboardNow()

        guard case .rejected(let error) = outcome else { Issue.record("expected a rejection, got \(outcome)"); return }
        #expect(error.code == .capLim001)
        #expect(await rig.itemCount() == 1)
        try await Task.sleep(for: .milliseconds(200))
        #expect(!rig.presenter.shown.contains("CAP-LIM-001"))
    }

    // MARK: AC-005-06 dedupe and no double ingest

    /// OC-WSC-009. given "same" captured by the poll (copyCount 1), when Save Clipboard runs on the same content, then
    /// `.saved`, still ONE row (count delta 0), `copyCount` 2 in a fresh database; and a later poll tick does not ingest
    /// the already-handled change again (copyCount stays 2). Red if a duplicate row appears, the bump is lost, or the
    /// poll re-ingests the saved change count.
    @Test("OC-WSC-009 saving an already-stored clip bumps copyCount, adds no row, and the poll does not repeat it")
    func alreadyStoredBumpsOnce() async throws {
        let rig = try await rig(mode: .active); defer { Task { await rig.cleanUp() } }
        rig.capture.start()
        rig.text("same")
        rig.capture.captureNow()
        #expect(await eventually { await rig.itemCount() == 1 })
        let before = try await rig.freshRows()
        #expect(before.map(\.copyCount) == [1])

        let outcome = await rig.capture.saveClipboardNow()
        #expect(outcome == .saved)
        rig.capture.captureNow()
        await rig.capture.stop()

        let after = try await rig.freshRows()
        #expect(after.count == 1)
        #expect(after.first?.contentKey == before.first?.contentKey)
        #expect(after.first?.copyCount == 2)
    }

    /// OC-WSC-010. given Active mode, a copy and a Save, when the poll ticks on the same change count, then
    /// nothing more is stored and the item's copyCount stays 1. Red if `saveClipboardNow` stops recording the handled
    /// change count (the poll would hit gate 1, but in Active mode it would re-ingest).
    @Test("OC-WSC-010 Active mode: the poll after Save Clipboard on the same change does not bump again")
    func pollAfterSaveDoesNotReingest() async throws {
        let rig = try await rig(mode: .active); defer { Task { await rig.cleanUp() } }
        rig.capture.start()
        rig.text("fresh")

        #expect(await rig.capture.saveClipboardNow() == .saved)
        rig.capture.captureNow()
        await rig.capture.stop()

        let rows = try await rig.freshRows()
        #expect(rows.map(\.plainText) == ["fresh"])
        #expect(rows.map(\.copyCount) == [1])
    }

    // MARK: FR-001-18(b) interaction

    /// OC-WSC-011. given ONE empty pasteboard change (a single changeCount), when the user presses Save Clipboard three
    /// times, then every press reports CAP-VAL-001: FR-001-18(b) suspends capture on three consecutive changeCount
    /// INCREMENTS that return no data, and a repeated user action on an unchanged clipboard is not three increments.
    /// Red if repeated Save presses on one empty clipboard suspend capture and raise CAP-PRM-001.
    @Test("OC-WSC-011 three Save presses on one empty clipboard do not suspend capture")
    func repeatedSaveOnOneEmptyChangeDoesNotSuspend() async throws {
        let rig = try await rig(mode: .curated); defer { Task { await rig.cleanUp() } }
        rig.pasteboard.copy([:])

        var codes: [ErrorCode] = []
        for _ in 0..<3 {
            if case .rejected(let error) = await rig.capture.saveClipboardNow() { codes.append(error.code) }
        }

        #expect(codes == [.capVal001, .capVal001, .capVal001])
    }
}
