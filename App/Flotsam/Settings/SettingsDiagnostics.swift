import FlotsamBase
import FlotsamStorage

/// Builds the diagnostics report and puts it on the pasteboard for About > Copy Diagnostics (FR-000-10).
enum SettingsDiagnostics {
    /// The pasteboard marker types FR-001-03 owns, from their one home in `PasteboardMarkers`.
    private static let ownWriteTypes = [PasteboardMarkers.autoGenerated, PasteboardMarkers.ownWrite]

    /// Answers the report's questions: permission states from the probe, per-kind counts and sizes from Storage.
    /// Counts and sizes only, never an item, a file name or a path (FR-000-10).
    private struct Source: DiagnosticsDataSource {
        let probe: any PermissionProbe
        let storage: SettingsStorage

        func permissionStates() async -> [PermissionName: PermissionState] {
            [
                .accessibility: probe.isGranted(.accessibility) ? .granted : .denied,
                .inputMonitoring: probe.isGranted(.inputMonitoring) ? .granted : .denied,
            ]
        }

        func itemCounts() async -> [ItemKind: Int] {
            guard case .success(let counts) = await storage.itemCounts() else { return [:] }
            return counts
        }

        func storageBytes() async -> (database: Int, blobs: Int) {
            guard case .success(let usage) = await storage.usage() else { return (0, 0) }
            return (Int(clamping: usage.databaseBytes), Int(clamping: usage.imageBytes))
        }
    }

    static func copy(
        settings: SettingsStore, probe: any PermissionProbe, storage: SettingsStorage, reporter: ErrorReporter
    ) async -> FlotsamResult<Int> {
        let builder = DiagnosticsSnapshotBuilder(
            settings: settings, source: Source(probe: probe, storage: storage),
            recentErrors: { await reporter.recentErrors() })
        let report = await builder.report()
        return await MainActor.run {
            DiagnosticsCopier(pasteboard: SystemPasteboard(), ownWriteTypes: ownWriteTypes).copy(report)
        }
    }
}
